// Generates static/robots.txt and static/sitemap.xml from the docs catalogue.
// Run with `bun run seo`. The /engines/* and other harness routes are test
// pages, not public docs, so they are disallowed and omitted from the sitemap.
// Every crawler, including AI search bots, is intentionally allowed: the site
// is small, MIT-licensed docs with no crawl-budget concern. No <lastmod> dates
// are emitted so generation stays byte-stable for the drift test.
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { PREVIEW_COMPONENTS } from '../../src/routes/components';
import { BASE_URL } from '../llms-txt/generate';

const DISALLOWED_PATHS = [
	'/engines/',
	'/bounding-box-citations/multi-page',
	'/schema-builder/controlled'
];

/** robots.txt allowing all crawlers and pointing at the sitemap. Pure. */
export function generateRobotsTxt(): string {
	const lines = [
		'# Extend UI Svelte docs — generated by `bun run seo`. Do not edit by hand.',
		'# Every crawler, including AI search bots, is welcome here; only test harness pages are excluded.',
		'User-agent: *',
		'Allow: /',
		'',
		...DISALLOWED_PATHS.map((path) => `Disallow: ${path}`),
		'',
		`Sitemap: ${BASE_URL}/sitemap.xml`
	];
	return `${lines.join('\n')}\n`;
}

function escapeXml(value: string): string {
	return value
		.replace(/&/g, '&amp;')
		.replace(/</g, '&lt;')
		.replace(/>/g, '&gt;')
		.replace(/"/g, '&quot;');
}

/** Sitemap covering the home page and every public docs page. Pure. */
export function generateSitemapXml(): string {
	const urls = [`${BASE_URL}/`, ...PREVIEW_COMPONENTS.map(({ slug }) => `${BASE_URL}/${slug}`)];
	const lines = [
		'<?xml version="1.0" encoding="UTF-8"?>',
		'<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
		...urls.map((url) => `  <url>\n    <loc>${escapeXml(url)}</loc>\n  </url>`),
		'</urlset>'
	];
	return `${lines.join('\n')}\n`;
}

const THIS_FILE = fileURLToPath(import.meta.url);
const invokedAsScript = process.argv[1]?.endsWith('scripts/seo/generate.ts') ?? false;

if (invokedAsScript) {
	const staticDir = join(dirname(THIS_FILE), '..', '..', 'static');
	writeFileSync(join(staticDir, 'robots.txt'), generateRobotsTxt());
	writeFileSync(join(staticDir, 'sitemap.xml'), generateSitemapXml());
	console.log('Wrote static/robots.txt and static/sitemap.xml');
}
